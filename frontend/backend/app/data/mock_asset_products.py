SNAPSHOT_TS = datetime.fromisoformat("2026-07-29T00:00:00+07:00")


def _common(
    *,
    product_id: str,
    asset_class: AssetClass,
    provider: str,
    product_name: str,
    expected_return: float,
    volatility: float,
    liquidity_score: int,
    minimum_investment: float,
    risk_level: str,
    execution_instruction: str,
    allocation_rule_type: AllocationRuleType = AllocationRuleType.FIXED_RETURN,
    allocation_segments: list[AllocationSegment] | None = None,
    maximum_investment: float | None = None,
    transaction_cost: float = 0,
    lockup_period: int = 0,
    early_exit_penalty: float = 0,
    eligibility_conditions: dict[str, Any] | None = None,
    timing_score: int | None = None,
    data_confidence: int = 80,
    max_weight_hint: float | None = None,
    product_base_id: str | None = None,
    qualifying_balance_scope: QualifyingBalanceScope = QualifyingBalanceScope.PER_CONTRACT,
    rounding_rule: RoundingRule = RoundingRule.VND_1K,
    repricing_required: bool = False,
    source_registry_id: str = "MOCK_ASSET_PRODUCT_2026Q3",
    source_reference: str = "Mock manually verified product data for hackathon demo.",
    rights_status: RightsStatus = RightsStatus.APPROVED,
    value_provenance: ValueProvenance = ValueProvenance.MANUAL_VERIFIED,
    verification_status: VerificationStatus = VerificationStatus.PARTIALLY_VERIFIED,
    uncertainty_bounds: UncertaintyBounds | None = None,
    buy_price: float | None = None,
    sell_price: float | None = None,
) -> AssetProduct:
    return AssetProduct(
        product_id=product_id,
        asset_class=asset_class,
        provider=provider,
        product_name=product_name,
        source_reference=source_reference,
        data_timestamp=SNAPSHOT_TS,
        buy_price=buy_price,
        sell_price=sell_price,
        expected_return=expected_return,
        volatility=volatility,
        liquidity_score=liquidity_score,
        minimum_investment=minimum_investment,
        maximum_investment=maximum_investment,
        transaction_cost=transaction_cost,
        lockup_period=lockup_period,
        early_exit_penalty=early_exit_penalty,
        eligibility_conditions=eligibility_conditions or {},
        risk_level=risk_level,  # type: ignore[arg-type]
        timing_score=timing_score,
        data_confidence=data_confidence,
        max_weight_hint=max_weight_hint,
        execution_instruction=execution_instruction,
        product_base_id=product_base_id,
        allocation_rule_type=allocation_rule_type,
        allocation_segments=allocation_segments or [],
        qualifying_balance_scope=qualifying_balance_scope,
        rounding_rule=rounding_rule,
        repricing_required=repricing_required,
        source_registry_id=source_registry_id,
        rights_status=rights_status,
        value_provenance=value_provenance,
        verification_status=verification_status,
        uncertainty_bounds=uncertainty_bounds,
    )


def _deposit_segments() -> list[AllocationSegment]:
    return [
        AllocationSegment(lower_bound=0, upper_bound=50_000_000, return_rate=0.038, cost=0, condition="< 50m VND"),
        AllocationSegment(lower_bound=50_000_000, upper_bound=200_000_000, return_rate=0.043, cost=0, condition="50m-200m VND"),
        AllocationSegment(lower_bound=200_000_000, upper_bound=None, return_rate=0.048, cost=0, condition=">= 200m VND"),
    ]


def _load_vn30_snapshot(data_dir: Path) -> dict[str, Any]:
    snapshot_path = data_dir / "vn30_snapshot.mock.json"
    return json.loads(snapshot_path.read_text(encoding="utf-8"))


